export const getPerson = (id: string) => PEOPLE.find((person) => person.id === id);

export const getCoach = (person: Person) =>
  person.coachId ? getPerson(person.coachId) : undefined;

export const getCoachees = (personId: string, includeAll = false) =>
  includeAll
    ? PEOPLE.filter((person) => person.role !== "admin")
    : PEOPLE.filter((person) => person.coachId === personId);

export const initials = (name: string) =>
  name
    .split(" ")
    .map((part) => part[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
